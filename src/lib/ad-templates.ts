/**
 * Recommend templates for a concrete product: keyword-signal hits (+2 each, format
 * built for the trait) stack with the goodFor category tie (+3), while templates
 * tuned for a DIFFERENT category are pushed down (-2). Pure and deterministic —
 * ties resolve by curated library order. Empty input → empty list (the UI hides
 * the row instead of showing fake "recommendations").
 */
export function recommendAdTemplates(
  input: { category?: string; productName?: string; sellingPoints?: string },
  limit = 4
): AdTemplate[] {
  const text = `${input.productName ?? ""} ${input.sellingPoints ?? ""}`.trim();
  const category = input.category;
  if (!text && !category) return [];
  const boosts = new Map<string, number>();
  if (text) {
    for (const rule of RECOMMEND_SIGNALS) {
      if (!rule.pattern.test(text)) continue;
      for (const id of rule.ids) boosts.set(id, (boosts.get(id) ?? 0) + 2);
    }
  }
  const scored = AD_TEMPLATES.map((t, i) => {
    let score = boosts.get(t.id) ?? 0;
    if (category && t.goodFor) score += t.goodFor.includes(category as AdTemplateCategory) ? 3 : -2;
    return { t, score, i };
  }).filter((s) => s.score > 0);
  scored.sort((a, b) => b.score - a.score || a.i - b.i);
  return scored.slice(0, limit).map((s) => s.t);
}

