/** Lookup by template id (undefined for unknown ids). */
export function getAdTemplate(id: string | undefined | null): AdTemplate | undefined {
  if (!id) return undefined;
  return AD_TEMPLATES.find((t) => t.id === id);
}

/**
 * Templates for the picker: optional group filter, optional keyword query
 * (matches bilingual name/tagline, case-insensitive), and with a product
 * category chosen, category-tuned templates float to the front (stable
 * partition — order inside each half is preserved, so curation order still
 * matters).
 */
export function listAdTemplates(opts?: { group?: AdTemplateGroupId | "all"; category?: string; query?: string }): AdTemplate[] {
  const group = opts?.group && opts.group !== "all" ? opts.group : undefined;
  let pool = group ? AD_TEMPLATES.filter((t) => t.group === group) : [...AD_TEMPLATES];
  const query = opts?.query?.trim().toLowerCase();
  if (query) {
    pool = pool.filter((t) =>
      [t.name.zh, t.name.en, t.tagline.zh, t.tagline.en].some((s) => s.toLowerCase().includes(query))
    );
  }
  const category = opts?.category;
  if (!category) return pool;
  return [
    ...pool.filter((t) => t.goodFor?.includes(category as AdTemplateCategory)),
    ...pool.filter((t) => !t.goodFor?.includes(category as AdTemplateCategory)),
  ];
}

